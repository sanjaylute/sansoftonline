import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const app = join(root, 'src/app');

function fixedPageDirectories(directory = app, relative = '') {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (!entry.isDirectory() || entry.name.startsWith('[') || entry.name === 'api') return [];
    const nextRelative = relative ? relative + '/' + entry.name : entry.name;
    const nextDirectory = join(directory, entry.name);
    const ownPage = readdirSync(nextDirectory).some((file) => file === 'page.tsx') ? [nextRelative] : [];
    return [...ownPage, ...fixedPageDirectories(nextDirectory, nextRelative)];
  });
}

function matchQuotedKeys(source) {
  return [...source.matchAll(/'([^']+)'\s*:/g)].map((match) => match[1]);
}

const pageDirectories = fixedPageDirectories().sort();
const remainingSource = readFileSync(join(root, 'src/lib/remaining-page-data.ts'), 'utf8');
const remainingSlugs = matchQuotedKeys(remainingSource.slice(0, remainingSource.indexOf('const extraBySlug')))
  .filter((slug) => /^[a-z0-9-]+$/.test(slug))
  .filter((slug, index, values) => values.indexOf(slug) === index);
const blogSource = readFileSync(join(root, 'src/lib/blog-slugs.ts'), 'utf8');
const blogSlugs = [...blogSource.matchAll(/'([^']+)'/g)].map((match) => match[1]);

const fixedPaths = ['/', ...pageDirectories.map((directory) => '/' + directory + '/')];
const dynamicPaths = [...remainingSlugs, ...blogSlugs].map((slug) => '/' + slug + '/');
const paths = [...new Set([...fixedPaths, ...dynamicPaths])];
const registry = [
  "// Generated by scripts/generate-localized-page-registry.mjs. Do not edit manually.",
  "import HomePage from '@/app/page';",
  ...pageDirectories.map((directory, index) => "import Page" + index + " from '@/app/" + directory + "/page';"),
  '',
  'export const localizedSourcePages = {',
  "  '/': HomePage,",
  ...pageDirectories.map((directory, index) => "  '/" + directory + "/': Page" + index + ","),
  '} as const;',
  '',
].join('\n');
const pathList = [
  '// Generated by scripts/generate-localized-page-registry.mjs. Do not edit manually.',
  'export const localizedPublicPaths = ' + JSON.stringify(paths, null, 2) + ' as const;',
  'export type LocalizedPath = (typeof localizedPublicPaths)[number];',
  '',
].join('\n');

writeFileSync(join(root, 'src/components/localized-source-pages.tsx'), registry);
writeFileSync(join(root, 'src/lib/localized-paths.ts'), pathList);
console.log('Generated ' + paths.length + ' localized public routes (' + fixedPaths.length + ' fixed and ' + dynamicPaths.length + ' dynamic).');
